// Byte-for-byte clone of the Sonix K75 (0c45:8006): three HID interfaces,
// all interrupt-IN at 1 ms, no OUT pipe (host->device rides EP0 control).
// Report descriptors captured in ../k75-descriptors.txt.
#include "tusb.h"

#define USB_VID 0x0C45
#define USB_PID 0x8006

enum { ITF_KEYBOARD = 0, ITF_MEDIA, ITF_VENDOR, ITF_COUNT };

