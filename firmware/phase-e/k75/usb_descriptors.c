// if2: vendor page 0xFF13, 64-byte input + output + feature reports.
static uint8_t const desc_hid_vendor[] = {
    0x06, 0x13, 0xFF, 0x09, 0x01, 0xA1, 0x01, 0x15, 0x00, 0x26, 0xFF, 0x00,
    0x75, 0x08, 0x95, 0x40, 0x09, 0x02, 0x81, 0x02, 0x09, 0x03, 0x91, 0x02,
    0x0A, 0x00, 0xFF, 0xB1, 0x02, 0xC0,
};

uint8_t const *tud_hid_descriptor_report_cb(uint8_t instance) {
    switch (instance) {
    case ITF_KEYBOARD: return desc_hid_keyboard;
    case ITF_MEDIA:    return desc_hid_media;
    default:           return desc_hid_vendor;
    }
}

#define CONFIG_TOTAL_LEN (TUD_CONFIG_DESC_LEN + 3 * TUD_HID_DESC_LEN)
#define EPNUM_KBD_IN    0x81
#define EPNUM_MEDIA_IN  0x82
#define EPNUM_VENDOR_IN 0x83

static uint8_t const desc_configuration[] = {
    TUD_CONFIG_DESCRIPTOR(1, ITF_COUNT, 0, CONFIG_TOTAL_LEN, TUSB_DESC_CONFIG_ATT_REMOTE_WAKEUP, 100),
    TUD_HID_DESCRIPTOR(ITF_KEYBOARD, 0, HID_ITF_PROTOCOL_KEYBOARD, sizeof(desc_hid_keyboard),
                       EPNUM_KBD_IN, 16, 1),
    TUD_HID_DESCRIPTOR(ITF_MEDIA, 0, HID_ITF_PROTOCOL_MOUSE, sizeof(desc_hid_media),
                       EPNUM_MEDIA_IN, 16, 1),
    // The real K75's EP3 is 8 bytes; 64 moves a whole vendor report in one
    // poll — the one deliberate divergence, for ACK latency.
    TUD_HID_DESCRIPTOR(ITF_VENDOR, 0, HID_ITF_PROTOCOL_NONE, sizeof(desc_hid_vendor),
                       EPNUM_VENDOR_IN, 64, 1),
};

uint8_t const *tud_descriptor_configuration_cb(uint8_t index) {
    (void)index;
    return desc_configuration;
}

static char const *string_desc[] = {
    (const char[]){0x09, 0x04}, // 0: English (US)
    "SONIX",                    // 1: manufacturer
    "K75",                      // 2: product
};

static uint16_t desc_str[32];

uint16_t const *tud_descriptor_string_cb(uint8_t index, uint16_t langid) {
    (void)langid;
    uint8_t chr_count;
    if (index == 0) {
        memcpy(&desc_str[1], string_desc[0], 2);
        chr_count = 1;
    } else {
        if (index >= sizeof(string_desc) / sizeof(string_desc[0])) return NULL;
        const char *str = string_desc[index];
        chr_count = (uint8_t)strlen(str);
        if (chr_count > 31) chr_count = 31;
        for (uint8_t i = 0; i < chr_count; i++) desc_str[1 + i] = str[i];
    }
    desc_str[0] = (uint16_t)((TUSB_DESC_STRING << 8) | (2 * chr_count + 2));
    return desc_str;
}
